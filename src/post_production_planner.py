# ==========================================================
# SCHEMA
# ==========================================================


POST_PRODUCTION_SCHEMA_VERSION = 2


# ==========================================================
# EXCEPTION
# ==========================================================


class PostProductionPlannerError(Exception):
    pass


# ==========================================================
# DATA MODELS
# ==========================================================


@dataclass(frozen=True)
class OverlayCue:
    """
    A VERIFIED exact graphic.

    text:
        Exact visible text to render.

    source_quote:
        Verbatim source from the user's original prompt.

    mode:
        editorial:
            Text is naturally presented as a graphic overlay.

        diegetic:
            Text belongs physically inside the scene:
            phone, screen, meter, sign, scoreboard, document,
            interface, package, etc.

    start/end:
        Local timing inside the scene.
    """

    scene_number: int

    text: str

    source_quote: str

    start: float

    end: float

    mode: str = "editorial"

    position: str = "bottom"

    style: str = "clean"

    purpose: str = ""


@dataclass(frozen=True)
class UnresolvedGraphic:
    """
    Something could benefit from an exact graphic, but the
    user did not provide the exact content.

    It is intentionally NOT rendered.
    """

    scene_number: Optional[int]

    purpose: str

    reason: str


@dataclass(frozen=True)
class PostProductionPlan:

    overlays: list[OverlayCue]

    unresolved_exact_graphics: list[
        UnresolvedGraphic
    ]

    notes: str = ""


# ==========================================================
# PLANNER
# ==========================================================


class PostProductionPlanner:
    """
    Professional, source-grounded post-production planner.

    Critical rule:

    Exact visible content must be grounded in the ORIGINAL
    USER PROMPT.

    The storyboard can help determine timing and placement,
    but it is not considered an authoritative source of
    exact values because it was itself generated by AI.
    """

    VALID_MODES = {
        "editorial",
        "diegetic",
    }

    VALID_POSITIONS = {
        "top",
        "top_left",
        "top_right",
        "center",
        "bottom",
        "bottom_left",
        "bottom_right",
    }

    VALID_STYLES = {
        "clean",
        "impact",
        "subtle",
    }

    MAX_OVERLAY_TEXT_LENGTH = 120

    def __init__(
        self,
        model: str = AGNES_TEXT_MODEL,
        timeout: int = 120,
    ) -> None:

        self.model = model

        self.timeout = timeout

        self.url = (
            f"{AGNES_BASE_URL}"
            "/v1/chat/completions"
        )

        self.headers = {
            "Authorization": (
                f"Bearer {AGNES_API_KEY}"
            ),
            "Content-Type": (
                "application/json"
            ),
        }

    # ======================================================
    # CREATE PLAN
    # ======================================================

    def create_plan(
        self,
        video_plan: VideoPlan,
        source_prompt: str,
    ) -> PostProductionPlan:

        source_prompt = (
            source_prompt
            or ""
        ).strip()

        if not source_prompt:

            raise PostProductionPlannerError(
                "The original user prompt is required "
                "for safe post-production planning."
            )

        storyboard = {
            "title": (
                video_plan.title
            ),
            "language": (
                video_plan.language
            ),
            "setting_description": (
                video_plan.setting_description
            ),
            "continuity_constraints": (
                video_plan.continuity_constraints
            ),
            "scenes": [
                {
                    "number": (
                        scene.number
                    ),
                    "duration": (
                        scene.duration
                    ),
                    "visual_prompt": (
                        scene.visual_prompt
                    ),
                    "start_state": (
                        scene.start_state
                    ),
                    "end_state": (
                        scene.end_state
                    ),
                    "dialogue": (
                        scene.dialogue
                    ),
                }
                for scene
                in video_plan.scenes
            ],
        }

        system_prompt = """
You are a professional video post-production supervisor.

Your task is to decide whether exact readable graphics
should be added to an AI-generated video.

You receive:

1. ORIGINAL USER PROMPT
2. AI-GENERATED STORYBOARD

The ORIGINAL USER PROMPT is the only authoritative source
for exact visible text, numbers, dates, prices, scores,
messages, labels and other exact factual values.

The storyboard may be used ONLY to determine:
- which scene is appropriate
- timing
- visual context
- whether the content is editorial or diegetic


============================================================
ABSOLUTE NON-INVENTION RULE
============================================================

NEVER invent an exact value.

NEVER invent:
- a price
- a score
- a date
- a percentage
- a number
- a time
- a phone number
- a measurement
- a quoted message
- a label
- a name
- a title
- a location name
- a result
- a statistic
- any exact readable content

Do not calculate or infer an exact value.

Do not choose a representative value.

Do not make an exaggerated value.

Do not create a comedic number.

Do not complete an unfinished fact.

Do not normalize or translate the content that will be
displayed.

If exact information would improve the video but the user
did not explicitly provide it, put it in:

unresolved_exact_graphics

It MUST NOT appear in overlays.


============================================================
SOURCE GROUNDING
============================================================

Every overlay MUST contain:

source_quote

source_quote must be copied from the ORIGINAL USER PROMPT.

The visible field:

text

must be an exact contiguous substring of source_quote.

Do not rewrite text.

Do not translate text.

Do not change currency notation.

Do not change punctuation.

Do not change numeric formatting.

Do not add units.

Do not remove units when doing so changes meaning.


============================================================
WHEN AN OVERLAY IS USEFUL
============================================================

Use an exact overlay only when readable information is
important to:

- comprehension
- narrative payoff
- factual accuracy
- navigation
- chronology
- score/result understanding
- an explicit user request for visible text

Do NOT automatically subtitle dialogue.

Do NOT add decorative text merely because it is possible.

Do NOT create generic titles unless the user's prompt
actually contains the exact title that should appear.


============================================================
DISPLAY MODE
============================================================

mode = "editorial"

Use when the graphic exists as video editing / presentation,
for example:

- chapter title
- location label
- lower third
- explanatory label
- score graphic intentionally presented to the viewer


mode = "diegetic"

Use when the text belongs to an object inside the fictional
or real scene, for example:

- phone screen
- computer monitor
- taxi meter
- scoreboard physically inside a stadium
- product label
- street sign
- document
- receipt
- clock
- machine display

Do not convert a diegetic graphic into editorial text just
because rendering it would be easier.


============================================================
TIMING
============================================================

start and end are LOCAL times within a scene.

Required:

0 <= start < end <= scene duration

Usually keep readable information visible for at least
1.5 seconds when scene duration permits.


============================================================
POSITION
============================================================

Allowed:

top
top_left
top_right
center
bottom
bottom_left
bottom_right

This position is only an editorial/safe-screen suggestion.

For diegetic elements, it does NOT represent true object
tracking.


============================================================
STYLE
============================================================

Allowed:

clean
impact
subtle


============================================================
UNRESOLVED EXACT GRAPHICS
============================================================

If the story clearly needs an exact visual value but the
original prompt does not contain that value, add:

{
  "scene_number": 5,
  "purpose": "describe what exact information is missing",
  "reason": "the original prompt does not specify the exact value"
}

Never provide a suggested replacement value.


============================================================
JSON FORMAT
============================================================

Return ONLY valid JSON.

No markdown.

No prose outside JSON.

Format:

{
  "overlays": [
    {
      "scene_number": 1,
      "text": "exact substring from user prompt",
      "source_quote": "exact quote copied from user prompt",
      "start": 1.5,
      "end": 4.0,
      "mode": "editorial",
      "position": "bottom",
      "style": "clean",
      "purpose": "brief explanation"
    }
  ],
  "unresolved_exact_graphics": [
    {
      "scene_number": 2,
      "purpose": "exact information that would be useful",
      "reason": "why it cannot safely be generated"
    }
  ],
  "notes": ""
}

If no exact overlay is justified:

{
  "overlays": [],
  "unresolved_exact_graphics": [],
  "notes": ""
}
""".strip()

        user_payload = {
            "original_user_prompt": (
                source_prompt
            ),
            "storyboard": (
                storyboard
            ),
        }

        raw = self._chat(
            system_prompt=(
                system_prompt
            ),
            user_prompt=json.dumps(
                user_payload,
                ensure_ascii=False,
                indent=2,
            ),
        )

        data = self._extract_json(
            raw
        )

        return self._parse(
            data=data,
            video_plan=(
                video_plan
            ),
            source_prompt=(
                source_prompt
            ),
        )

    # ======================================================
    # CHAT
    # ======================================================

    def _chat(
        self,
        system_prompt: str,
        user_prompt: str,
    ) -> str:

        payload = {
            "model": (
                self.model
            ),
            "messages": [
                {
                    "role": "system",
                    "content": (
                        system_prompt
                    ),
                },
                {
                    "role": "user",
                    "content": (
                        user_prompt
                    ),
                },
            ],
            "temperature": 0.0,
            "max_tokens": 3000,
        }

        try:

            response = requests.post(
                self.url,
                headers=(
                    self.headers
                ),
                json=payload,
                timeout=(
                    self.timeout
                ),
            )

        except requests.RequestException as exc:

            raise PostProductionPlannerError(
                "Unable to contact Agnes "
                f"text model: {exc}"
            ) from exc

        if not response.ok:

            raise PostProductionPlannerError(
                "Agnes post-production planning "
                "request failed. "
                f"HTTP {response.status_code}: "
                f"{response.text}"
            )

        try:

            result = (
                response.json()[
                    "choices"
                ][0][
                    "message"
                ][
                    "content"
                ]
            )

            return str(
                result
            )

        except (
            ValueError,
            KeyError,
            IndexError,
            TypeError,
        ) as exc:

            raise PostProductionPlannerError(
                "Unexpected Agnes response "
                "while planning post-production."
            ) from exc

    # ======================================================
    # JSON EXTRACTION
    # ======================================================

    @staticmethod
    def _extract_json(
        text: str,
    ) -> dict:

        text = (
            text
            or ""
        ).strip()

        text = re.sub(
            r"^```(?:json)?\s*",
            "",
            text,
            flags=(
                re.IGNORECASE
            ),
        )

        text = re.sub(
            r"\s*```$",
            "",
            text,
        )

        try:

            result = json.loads(
                text
            )

        except json.JSONDecodeError:

            start = text.find(
                "{"
            )

            end = text.rfind(
                "}"
            )

            if (
                start < 0
                or end <= start
            ):

                raise PostProductionPlannerError(
                    "No valid JSON object found "
                    "in Agnes response."
                )

            try:

                result = json.loads(
                    text[
                        start:
                        end + 1
                    ]
                )

            except json.JSONDecodeError as exc:

                raise PostProductionPlannerError(
                    "Agnes returned invalid "
                    "post-production JSON."
                ) from exc

        if not isinstance(
            result,
            dict,
        ):

            raise PostProductionPlannerError(
                "Post-production JSON root "
                "must be an object."
            )

        return result

    # ======================================================
    # NORMALIZATION FOR VALIDATION
    # ======================================================

    @staticmethod
    def _normalize_for_match(
        value: str,
    ) -> str:

        value = unicodedata.normalize(
            "NFKC",
            value or "",
        )

        value = re.sub(
            r"\s+",
            " ",
            value,
        )

        return value.strip()

    # ======================================================
    # SOURCE VALIDATION
    # ======================================================

    def _is_grounded(
        self,
        source_prompt: str,
        source_quote: str,
        text: str,
    ) -> bool:

        prompt_norm = (
            self._normalize_for_match(
                source_prompt
            )
        )

        quote_norm = (
            self._normalize_for_match(
                source_quote
            )
        )

        text_norm = (
            self._normalize_for_match(
                text
            )
        )

        if not quote_norm:

            return False

        if not text_norm:

            return False

        # Quote must actually come from prompt.
        if (
            quote_norm
            not in prompt_norm
        ):

            return False

        # Displayed text must be contained inside
        # the verified source quote.
        if (
            text_norm
            not in quote_norm
        ):

            return False

        return True

    # ======================================================
    # PARSE + PROGRAMMATIC SAFETY
    # ======================================================

    def _parse(
        self,
        data: dict,
        video_plan: VideoPlan,
        source_prompt: str,
    ) -> PostProductionPlan:

        scene_map = {
            scene.number: scene
            for scene
            in video_plan.scenes
        }

        overlays: list[
            OverlayCue
        ] = []

        seen = set()

        raw_overlays = (
            data.get(
                "overlays",
                [],
            )
        )

        if not isinstance(
            raw_overlays,
            list,
        ):

            raw_overlays = []

        for raw in (
            raw_overlays
        ):

            if not isinstance(
                raw,
                dict,
            ):

                continue

            # ----------------------------------------------
            # BASIC FIELDS
            # ----------------------------------------------

            try:

                scene_number = int(
                    raw.get(
                        "scene_number"
                    )
                )

                start = float(
                    raw.get(
                        "start"
                    )
                )

                end = float(
                    raw.get(
                        "end"
                    )
                )

            except (
                TypeError,
                ValueError,
            ):

                continue

            scene = (
                scene_map.get(
                    scene_number
                )
            )

            if scene is None:

                continue

            text = str(
                raw.get(
                    "text",
                    "",
                )
            ).strip()

            source_quote = str(
                raw.get(
                    "source_quote",
                    "",
                )
            ).strip()

            # ----------------------------------------------
            # CRITICAL GROUNDING CHECK
            # ----------------------------------------------

            if not self._is_grounded(
                source_prompt=(
                    source_prompt
                ),
                source_quote=(
                    source_quote
                ),
                text=text,
            ):

                print()

                print(
                    "Rejected ungrounded "
                    "post-production overlay:"
                )

                print(
                    f'Text: "{text}"'
                )

                print(
                    "Reason: value was not verified "
                    "against the original user prompt."
                )

                print()

                continue

            # ----------------------------------------------
            # TEXT SAFETY
            # ----------------------------------------------

            if (
                len(text)
                >
                self.MAX_OVERLAY_TEXT_LENGTH
            ):

                continue

            if not re.search(
                r"\w",
                text,
                flags=(
                    re.UNICODE
                ),
            ):

                continue

            # ----------------------------------------------
            # TIMING
            # ----------------------------------------------

            scene_duration = float(
                scene.duration
            )

            start = max(
                0.0,
                min(
                    start,
                    scene_duration,
                ),
            )

            end = max(
                0.0,
                min(
                    end,
                    scene_duration,
                ),
            )

            if end <= start:

                continue

            # ----------------------------------------------
            # MODE
            # ----------------------------------------------

            mode = str(
                raw.get(
                    "mode",
                    "editorial",
                )
            ).strip().lower()

            if (
                mode
                not in self.VALID_MODES
            ):

                mode = (
                    "editorial"
                )

            # ----------------------------------------------
            # POSITION
            # ----------------------------------------------

            position = str(
                raw.get(
                    "position",
                    "bottom",
                )
            ).strip().lower()

            if (
                position
                not in self.VALID_POSITIONS
            ):

                position = (
                    "bottom"
                )

            # ----------------------------------------------
            # STYLE
            # ----------------------------------------------

            style = str(
                raw.get(
                    "style",
                    "clean",
                )
            ).strip().lower()

            if (
                style
                not in self.VALID_STYLES
            ):

                style = (
                    "clean"
                )

            purpose = str(
                raw.get(
                    "purpose",
                    "",
                )
            ).strip()

            # ----------------------------------------------
            # DEDUPLICATION
            # ----------------------------------------------

            signature = (
                scene_number,
                self._normalize_for_match(
                    text
                ),
                round(
                    start,
                    2,
                ),
                round(
                    end,
                    2,
                ),
                mode,
            )

            if signature in seen:

                continue

            seen.add(
                signature
            )

            overlays.append(
                OverlayCue(
                    scene_number=(
                        scene_number
                    ),
                    text=text,
                    source_quote=(
                        source_quote
                    ),
                    start=round(
                        start,
                        3,
                    ),
                    end=round(
                        end,
                        3,
                    ),
                    mode=mode,
                    position=(
                        position
                    ),
                    style=style,
                    purpose=(
                        purpose
                    ),
                )
            )

        # ==================================================
        # UNRESOLVED GRAPHICS
        # ==================================================

        unresolved = []

        raw_unresolved = (
            data.get(
                "unresolved_exact_graphics",
                [],
            )
        )

        if not isinstance(
            raw_unresolved,
            list,
        ):

            raw_unresolved = []

        for raw in raw_unresolved:

            if not isinstance(
                raw,
                dict,
            ):

                continue

            scene_number = (
                raw.get(
                    "scene_number"
                )
            )

            if scene_number is not None:

                try:

                    scene_number = int(
                        scene_number
                    )

                except (
                    TypeError,
                    ValueError,
                ):

                    scene_number = None

                if (
                    scene_number
                    not in scene_map
                ):

                    scene_number = None

            purpose = str(
                raw.get(
                    "purpose",
                    "",
                )
            ).strip()

            reason = str(
                raw.get(
                    "reason",
                    "",
                )
            ).strip()

            if not purpose:

                continue

            unresolved.append(
                UnresolvedGraphic(
                    scene_number=(
                        scene_number
                    ),
                    purpose=(
                        purpose
                    ),
                    reason=(
                        reason
                    ),
                )
            )

        return PostProductionPlan(
            overlays=overlays,
            unresolved_exact_graphics=(
                unresolved
            ),
            notes=str(
                data.get(
                    "notes",
                    "",
                )
            ).strip(),
        )

    # ======================================================
    # SAVE
    # ======================================================

    @staticmethod
    def save(
        plan: PostProductionPlan,
        path: Path,
    ) -> None:

        path = Path(
            path
        )

        path.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        data = {
            "schema_version": (
                POST_PRODUCTION_SCHEMA_VERSION
            ),
            **asdict(
                plan
            ),
        }

        temporary = Path(
            str(path)
            + ".tmp"
        )

        temporary.write_text(
            json.dumps(
                data,
                ensure_ascii=False,
                indent=2,
            ),
            encoding="utf-8",
        )

        temporary.replace(
            path
        )

    # ======================================================
    # LOAD
    # ======================================================

    @staticmethod
    def load(
        path: Path,
    ) -> PostProductionPlan:

        try:

            data = json.loads(
                Path(
                    path
                ).read_text(
                    encoding="utf-8"
                )
            )

        except (
            OSError,
            json.JSONDecodeError,
        ) as exc:

            raise PostProductionPlannerError(
                "Unable to read saved "
                "post-production plan."
            ) from exc

        schema_version = (
            data.get(
                "schema_version"
            )
        )

        if (
            schema_version
            !=
            POST_PRODUCTION_SCHEMA_VERSION
        ):

            raise PostProductionPlannerError(
                "Saved post-production plan "
                "uses an obsolete schema."
            )

        overlays = []

        for raw in (
            data.get(
                "overlays",
                []
            )
        ):

            overlays.append(
                OverlayCue(
                    scene_number=int(
                        raw[
                            "scene_number"
                        ]
                    ),
                    text=str(
                        raw[
                            "text"
                        ]
                    ),
                    source_quote=str(
                        raw[
                            "source_quote"
                        ]
                    ),
                    start=float(
                        raw[
                            "start"
                        ]
                    ),
                    end=float(
                        raw[
                            "end"
                        ]
                    ),
                    mode=str(
                        raw.get(
                            "mode",
                            "editorial",
                        )
                    ),
                    position=str(
                        raw.get(
                            "position",
                            "bottom",
                        )
                    ),
                    style=str(
                        raw.get(
                            "style",
                            "clean",
                        )
                    ),
                    purpose=str(
                        raw.get(
                            "purpose",
                            "",
                        )
                    ),
                )
            )

        unresolved = []

        for raw in (
            data.get(
                "unresolved_exact_graphics",
                []
            )
        ):

            unresolved.append(
                UnresolvedGraphic(
                    scene_number=(
                        raw.get(
                            "scene_number"
                        )
                    ),
                    purpose=str(
                        raw.get(
                            "purpose",
                            "",
                        )
                    ),
                    reason=str(
                        raw.get(
                            "reason",
                            "",
                        )
                    ),
                )
            )

        return PostProductionPlan(
            overlays=(
                overlays
            ),
            unresolved_exact_graphics=(
                unresolved
            ),
            notes=str(
                data.get(
                    "notes",
                    "",
                )
            ),
        )